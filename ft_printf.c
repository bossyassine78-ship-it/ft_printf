#include "ft_printf.h"

int	ft_printf(char const *format, ...)
{
	va_list	ap;
	int		count;

	if (!format)
		return (-1);
	count = 0;
	va_start(ap, format);
	count = print_argument(format, &ap);
	va_end(ap);
	return (count);
}
